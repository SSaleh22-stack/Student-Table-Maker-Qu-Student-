/**
 * Bundles two of the extension's content scripts into strings the app injects into the
 * student portal WebView:
 * - the course extractor (../src/content/extractCourses.ts), used by the import screen
 * - the course evaluation auto-fill (../src/content/reviewAutofill.ts), used by تقييم المقررات
 *
 * Run after changing the extractor:  npm run build:extractor
 * (esbuild comes from the extension's dependencies in the repo root.)
 */
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../src/content/extractCourses.ts');
const out = resolve(here, '../src/lib/portal/extractor.generated.ts');

const result = await build({
  stdin: {
    contents: `import { extractCoursesFromDom } from ${JSON.stringify(source)};\nwindow.__quExtract = extractCoursesFromDom;`,
    resolveDir: here,
    loader: 'ts',
  },
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2017',
  minify: true,
  write: false,
  logLevel: 'warning',
});

const code = result.outputFiles[0].text.trim();
writeFileSync(
  out,
  `// Generated by scripts/build-extractor.mjs from src/content/extractCourses.ts. Do not edit.\n` +
    `// Defines window.__quExtract(document) inside the portal page.\n` +
    `export const EXTRACTOR_BUNDLE = ${JSON.stringify(code)};\n`,
);
console.log(`Wrote ${out} (${code.length} chars)`);

// Course evaluation auto-fill: runs on its own when injected (it adds its button to the
// evaluation page and guards against running twice).
const reviewSource = resolve(here, '../../src/content/reviewAutofill.ts');
const reviewOut = resolve(here, '../src/lib/portal/reviewAutofill.generated.ts');
const review = await build({
  entryPoints: [reviewSource],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2017',
  minify: true,
  write: false,
  logLevel: 'warning',
});
const reviewCode = review.outputFiles[0].text.trim();
writeFileSync(
  reviewOut,
  `// Generated by scripts/build-extractor.mjs from src/content/reviewAutofill.ts. Do not edit.
` +
    `// Adds the "fill all" course evaluation button to the student portal page.
` +
    `export const REVIEW_AUTOFILL_BUNDLE = ${JSON.stringify(reviewCode)};
`,
);
console.log(`Wrote ${reviewOut} (${reviewCode.length} chars)`);
