/**
 * Native settings for the notebook (المذكرات) that no package plugin covers.
 *
 * Android: notebooks are kept out of Android Auto Backup and device-to-device extraction. They are
 * backed up only to the student's own Google Drive, when the student turns backup on (NB-85,
 * NB-86a), and Auto Backup's 25 MB quota would otherwise be filled by PDFs and audio, which stops
 * every other backup. The recorder's temporary files are excluded too.
 *
 * iOS: LSSupportsOpeningDocumentsInPlace=false, so a PDF or .qunote opened from Files or another
 * app is copied into the app's Inbox instead of being edited in place. This plugin is the only
 * writer of that key.
 */
import fs from 'node:fs';
import path from 'node:path';
import {
  type ConfigPlugin,
  createRunOncePlugin,
  withAndroidManifest,
  withDangerousMod,
  withInfoPlist,
} from 'expo/config-plugins';

const BACKUP_RULES = 'qu_backup_rules';
const EXTRACTION_RULES = 'qu_data_extraction_rules';

/**
 * Paths excluded from backup:
 * - file/notebooks/   Paths.document/notebooks (expo-file-system documents = Context.filesDir)
 * - file/Audio/       expo-audio recordings when the recorder is given directory 'document'
 * - root/cache/Audio/ expo-audio's default recording folder (Context.cacheDir/Audio)
 */
const EXCLUDES: readonly { domain: string; path: string }[] = [
  { domain: 'file', path: 'notebooks/' },
  { domain: 'file', path: 'Audio/' },
  { domain: 'root', path: 'cache/Audio/' },
];

const excludeLines = (indent: string): string =>
  EXCLUDES.map((e) => `${indent}<exclude domain="${e.domain}" path="${e.path}" />`).join('\n');

/** Android 11 and below (android:fullBackupContent). */
export const backupRulesXml = (): string =>
  [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/withNotebookNative.ts. Do not edit. -->',
    '<full-backup-content>',
    excludeLines('  '),
    '</full-backup-content>',
    '',
  ].join('\n');

/** Android 12 and above (android:dataExtractionRules). */
export const dataExtractionRulesXml = (): string =>
  [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/withNotebookNative.ts. Do not edit. -->',
    '<data-extraction-rules>',
    '  <cloud-backup>',
    excludeLines('    '),
    '  </cloud-backup>',
    '  <device-transfer>',
    excludeLines('    '),
    '  </device-transfer>',
    '</data-extraction-rules>',
    '',
  ].join('\n');

const withBackupRuleFiles: ConfigPlugin = (config) =>
  withDangerousMod(config, [
    'android',
    async (cfg) => {
      const xmlDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      await fs.promises.mkdir(xmlDir, { recursive: true });
      await fs.promises.writeFile(path.join(xmlDir, `${BACKUP_RULES}.xml`), backupRulesXml(), 'utf8');
      await fs.promises.writeFile(path.join(xmlDir, `${EXTRACTION_RULES}.xml`), dataExtractionRulesXml(), 'utf8');
      return cfg;
    },
  ]);

const withBackupRuleAttributes: ConfigPlugin = (config) =>
  withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (!app) throw new Error('withNotebookNative: AndroidManifest.xml has no <application> element.');
    app.$['android:fullBackupContent'] = `@xml/${BACKUP_RULES}`;
    app.$['android:dataExtractionRules'] = `@xml/${EXTRACTION_RULES}`;
    return cfg;
  });

const withOpenDocumentsAsCopies: ConfigPlugin = (config) =>
  withInfoPlist(config, (cfg) => {
    cfg.modResults.LSSupportsOpeningDocumentsInPlace = false;
    return cfg;
  });

const withNotebookNative: ConfigPlugin = (config) => {
  config = withBackupRuleFiles(config);
  config = withBackupRuleAttributes(config);
  return withOpenDocumentsAsCopies(config);
};

export default createRunOncePlugin(withNotebookNative, 'withNotebookNative', '1.0.0');
